#!/usr/bin/env node

import fs from 'fs';

const GENERATED_DIR = '.generated';
const GENERATED_CONTENT = `${GENERATED_DIR}/content.ts`;

// Read the extension version from the manifest so the stamp stays accurate
const manifestVersion = JSON.parse(fs.readFileSync('manifest.json', 'utf8')).version;

// Read all the modular files
const sharedDebug = fs.readFileSync('src/shared/debug.ts', 'utf8');
const sharedUtils = fs.readFileSync('src/shared/utils.ts', 'utf8');
const facebookModule = fs.readFileSync('src/platforms/facebook.ts', 'utf8');
const nextdoorModule = fs.readFileSync('src/platforms/nextdoor.ts', 'utf8');
const craigslistModule = fs.readFileSync('src/platforms/craigslist.ts', 'utf8');
const router = fs.readFileSync('src/router.ts', 'utf8');

// Remove import/export statements and combine
const removeImports = (content) => {
  return content
    .replace(/import\s*{[^}]*}\s*from\s*['"][^'"]*['"];?\s*/g, '')
    .replace(/import\s*[^;]*;?\s*/g, '')
    .replace(/export\s+/g, '');
};

// Remove duplicate constant declarations from platform files
const removeDuplicateConstants = (content) => {
  return content
    .replace(/export const SharedMsgAction = \{[\s\S]*?\};?\s*/g, '')
    .replace(/export const FacebookMsgAction = \{[\s\S]*?\};?\s*/g, '')
    .replace(/export const NextdoorMsgAction = \{[\s\S]*?\};?\s*/g, '')
    .replace(/export const CraigslistMsgAction = \{[\s\S]*?\};?\s*/g, '')
    .replace(/const FacebookMsgAction = \{[\s\S]*?\};?\s*/g, '')
    .replace(/const NextdoorMsgAction = \{[\s\S]*?\};?\s*/g, '')
    .replace(/const CraigslistMsgAction = \{[\s\S]*?\};?\s*/g, '')
    .replace(/as const;?\s*/g, '');
};

const combinedContent = `// ============================================================================
// MARKETPLACE HELPER CONTENT SCRIPT - MODULAR ORGANIZATION
// ============================================================================
// This file is automatically generated from modular source files
// Source files are in: src/shared/utils.ts, src/platforms/*.ts, src/router.ts
// Build timestamp: ${new Date().toISOString()}
// Version: ${manifestVersion}

${removeImports(sharedDebug)}

${removeImports(sharedUtils)}

// ============================================================================
// CONSTANT DECLARATIONS (from platform files)
// ============================================================================
const FacebookMsgAction = {
  fillFacebookForm: 'fillFacebookForm',
  uploadFacebookPhotos: 'uploadFacebookPhotos',
  clickMoreDetails: 'clickMoreDetails'
};

const NextdoorMsgAction = {
  fillNextdoorForm: 'fillNextdoorForm',
  uploadNextdoorPhotos: 'uploadNextdoorPhotos',
  handleNextdoorNavigation: 'handleNextdoorNavigation',
  checkNextdoorListingPage: 'checkNextdoorListingPage'
};

const CraigslistMsgAction = {
  fillCraigslistForm: 'fillCraigslistForm',
  uploadCraigslistPhotos: 'uploadCraigslistPhotos',
  clickCraigslistPostAd: 'clickCraigslistPostAd',
  selectCraigslistPostingType: 'selectCraigslistPostingType',
  chooseCraigslistCategory: 'chooseCraigslistCategory',
  checkCraigslistPostingPage: 'checkCraigslistPostingPage'
};

// ============================================================================
// FACEBOOK PLATFORM MODULE
// ============================================================================
${removeDuplicateConstants(removeImports(facebookModule))}

// ============================================================================
// NEXTDOOR PLATFORM MODULE
// ============================================================================
${removeDuplicateConstants(removeImports(nextdoorModule))}

// ============================================================================
// CRAIGSLIST PLATFORM MODULE
// ============================================================================
${removeDuplicateConstants(removeImports(craigslistModule))}

// ============================================================================
// MAIN ROUTER
// ============================================================================
${removeImports(router)}

// ============================================================================
// MESSAGE HANDLER (Added by build script)
// ============================================================================
// Main unified message handler
const handleMessage = (request: any, _sender: any, sendResponse: any) => {
  const currentPlatform = detectPlatform(window.location.href);
  debugLog(\`[DD] 🎯 Message received in \${currentPlatform} content script!\`);
  console.debug('📨 Content script received message:', request);

  if (request.action === SharedMsgAction.ping) {
    console.debug('🏓 Ping received, responding...');
    sendResponse({ success: true, message: \`\${currentPlatform} content script is loaded\`, timestamp: Date.now() });
  } else if (request.action === SharedMsgAction.detectPage) {
    console.debug('🔍 Page detection request received');
    const pageInfo = {
      url: window.location.href,
      title: document.title,
      site: currentPlatform,
      page: window.location.href.includes('marketplace/create') || window.location.href.includes('for_sale_and_free') || window.location.href.includes('post') ? 'marketplace_create' : 'unknown',
      ready: true
    };
    sendResponse(pageInfo);
  } else if (request.action === FacebookMsgAction.clickMoreDetails) {
    console.debug('🔍 Click More Details request received');
    const result = clickMoreDetailsButton();
    sendResponse(result);
  } else if (request.action === FacebookMsgAction.uploadFacebookPhotos) {
    debugLog('[DD] 🎯 uploadFacebookPhotos action received!');
    debugLog('[DD] 📋 Request data:', request.data);
    (async () => {
      const result = await uploadFacebookPhotos(request.data);
      sendResponse(result);
    })();
    return true;
  } else if (request.action === FacebookMsgAction.fillFacebookForm) {
    debugLog('[DD] 🎯 fillFacebookForm action received!');
    debugLog('[DD] 📋 Request data:', request.data);
    try {
      const results = fillFacebookForm(request.data);
      debugLog('[DD] 📊 Form fill results:', results);
      sendResponse({ success: true, result: results });
    } catch (error: any) {
      console.error('[DD] ❌ Form fill error:', error);
      sendResponse({ success: false, error: error.message });
    }
  } else if (request.action === NextdoorMsgAction.fillNextdoorForm) {
    debugLog('[DD] 🎯 fillNextdoorForm action received!');
    debugLog('[DD] 📋 Request data:', request.data);
    (async () => {
      const result = await fillNextdoorForm(request.data);
      sendResponse(result);
    })();
    return true;
  } else if (request.action === NextdoorMsgAction.uploadNextdoorPhotos) {
    debugLog('[DD] 🎯 uploadNextdoorPhotos action received!');
    debugLog('[DD] 📋 Request data:', request.data);
    (async () => {
      const result = await uploadNextdoorPhotos(request.data);
      sendResponse(result);
    })();
    return true;
  } else if (request.action === NextdoorMsgAction.handleNextdoorNavigation) {
    debugLog('[DD] 🎯 handleNextdoorNavigation action received!');
    (async () => {
      const result = await handleNextdoorNavigation();
      sendResponse(result);
    })();
    return true;
  } else if (request.action === NextdoorMsgAction.checkNextdoorListingPage) {
    debugLog('[DD] 🎯 checkNextdoorListingPage action received!');
    const result = checkNextdoorListingPage();
    sendResponse(result);
  } else if (request.action === CraigslistMsgAction.fillCraigslistForm) {
    debugLog('[DD] 🎯 fillCraigslistForm action received!');
    debugLog('[DD] 📋 Request data:', request.data);
    const result = fillCraigslistForm(request.data);
    sendResponse(result);
  } else if (request.action === CraigslistMsgAction.uploadCraigslistPhotos) {
    debugLog('[DD] 🎯 uploadCraigslistPhotos action received!');
    debugLog('[DD] 📋 Request data:', request.data);
    (async () => {
      const result = await uploadCraigslistPhotos(request.data);
      sendResponse(result);
    })();
    return true;
  } else if (request.action === CraigslistMsgAction.clickCraigslistPostAd) {
    debugLog('[DD] 🎯 clickCraigslistPostAd action received!');
    const result = clickCraigslistPostAd();
    sendResponse(result);
  } else if (request.action === CraigslistMsgAction.selectCraigslistPostingType) {
    debugLog('[DD] 🎯 selectCraigslistPostingType action received!');
    const result = selectCraigslistPostingType();
    sendResponse(result);
  } else if (request.action === CraigslistMsgAction.chooseCraigslistCategory) {
    debugLog('[DD] 🎯 chooseCraigslistCategory action received!');
    debugLog('[DD] 📋 Request data:', request.data);
    const result = chooseCraigslistCategory(request.data);
    sendResponse(result);
  } else if (request.action === CraigslistMsgAction.checkCraigslistPostingPage) {
    debugLog('[DD] 🎯 checkCraigslistPostingPage action received!');
    const result = checkCraigslistPostingPage();
    sendResponse(result);
  } else {
    console.debug('❓ Unknown action:', request.action);
    sendResponse({ success: false, error: 'Unknown action: ' + request.action });
  }
  return true;
};



// ============================================================================
// MESSAGE LISTENER SETUP (Added by build script)
// ============================================================================
debugLog('[DD] 🎯 Setting up message listener immediately...');
try {
  chrome.runtime.onMessage.addListener(handleMessage);
  debugLog('[DD] ✅ Message listener set up successfully!');
} catch (error) {
  console.error('[DD] ❌ Error setting up message listener:', error);
}
`;

// Keep generated code out of the source tree so builds do not dirty Git.
fs.mkdirSync(GENERATED_DIR, { recursive: true });
fs.writeFileSync(GENERATED_CONTENT, combinedContent);
console.log(`✅ Combined modular files into ${GENERATED_CONTENT}`);
